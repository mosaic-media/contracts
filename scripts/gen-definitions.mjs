/*
 * Generate ts/definitions.gen.ts — the standard component library as one
 * importable module, for JavaScript consumers that need it without a Platform
 * to push it (the storybook, a design tool, a test harness).
 *
 * The definitions themselves are authored ONCE, as definitions/*.json. This is
 * an aggregate of those files and nothing else: the Go side gets the same thing
 * through definitions.Library(), and neither is a place to add a component.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "definitions");

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort();

const defs = files.map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")));

const out = `// Code generated by scripts/gen-definitions.mjs from definitions/*.json. DO NOT EDIT.
// SPDX-License-Identifier: Apache-2.0
// SPDX-FileCopyrightText: 2026 the Mosaic authors

import type { ComponentDefinition } from "./contract.gen.js";

/** The standard component library: every component, as data. A client registers
 *  these and can then render any screen the Platform emits. The Platform serves
 *  the same library over the session (contracts#4), which is the path a running
 *  client uses; this module is for a consumer with no Platform to ask. */
export const DEFINITIONS: ComponentDefinition[] = ${JSON.stringify(defs, null, 2)};
`;

writeFileSync(join(root, "ts/definitions.gen.ts"), out);
console.log(`wrote ts/definitions.gen.ts (${defs.length} definitions)`);
